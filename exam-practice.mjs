export const examVariants=Object.freeze(patterns.map(({create,...meta})=>Object.freeze(meta)));
export function generateExamVariant(id,rng=Math.random){
 const pattern=patterns.find(p=>p.id===id);if(!pattern)throw new Error('Unknown exam variant '+id);
 const random=()=>Math.max(0,Math.min(.999999999,Number(rng())||0));
 const int=(a,b)=>a+Math.floor(random()*(b-a+1));
 return {...pattern.create({int,pick:a=>a[int(0,a.length-1)]}),skill:pattern.skill,examVariant:pattern.id,challenge:(pattern.extension?'★ 教材拓展 · ':'')+pattern.focus};
}
export function examForSkill(skill,rng=Math.random){
 const available=patterns.filter(p=>p.skill===skill);if(!available.length)return null;
 const value=Math.max(0,Math.min(.999999999,Number(rng())||0));
 return generateExamVariant(available[Math.floor(value*available.length)].id,rng);
}
export function referenceFor(q){
 const pattern=examVariants.find(p=>p.id===q?.examVariant&&p.skill===q?.skill);if(!pattern)return null;
 const source=examSources.find(s=>s.id===pattern.sourceId);
 return {...source,item:pattern.item,focus:pattern.focus};
}
